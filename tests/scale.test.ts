import assert from "node:assert/strict";
import { mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import test from "node:test";

test("a send journals both legs, the cache answers, and GraphQL reads the chain", async () => {
  delete process.env.ZENDO_DATABASE_URL;
  delete process.env.ZENDO_DATABASE_REPLICA_URL;
  delete process.env.ZENDO_REDIS_URL;
  delete process.env.REDIS_URL;
  delete process.env.ZENDO_GRPC_PORT;
  process.env.ZENDO_DISABLE_TIMER = "1";
  process.env.ZENDO_DATA_DIR = mkdtempSync(path.join(tmpdir(), "zendo-scale-"));
  const { cacheGet, cacheSet } = await import("../lib/cache.ts");
  await cacheSet("scale-probe", "ok", 30);
  assert.equal(await cacheGet("scale-probe"), "ok");
  const engine = await import("../lib/engine.ts");
  await engine.testingReset();
  const { ZENDO_OPERATOR } = await import("../lib/seed.ts");
  const operator = await engine.userByEmail(ZENDO_OPERATOR.email);
  assert.ok(operator);
  const dest = `znd1${"9a".repeat(19)}`;
  await engine.send(operator.id, dest, "ZCOIN", "1");
  const { readState } = await import("../lib/state.ts");
  const ledger = readState();
  assert.ok(ledger);
  const { journalBalances } = await import("../lib/double-entry.ts");
  assert.equal(ledger.journal.length, 2);
  assert.equal(journalBalances(ledger.journal), true);
  const { openLedger } = await import("../lib/ledger-store.ts");
  const row = openLedger().prepare("SELECT COUNT(*) AS n FROM transfers").get() as { n: number | bigint };
  assert.equal(Number(row.n), 2);
  const { runQuery } = await import("../lib/graphql.ts");
  const result = await runQuery("{ live { chain { networkId } } }");
  const data = result.data as { live?: { chain?: { networkId?: string } } } | null | undefined;
  assert.equal(result.errors, undefined);
  assert.equal(data?.live?.chain?.networkId, "zendo-1");
});
